const A = RELIEF.ALERT;
const SEV = A.SEVERITY_ORDER;
const SCOPE_RANK = { local: 0, regional: 1, nationwide: 2 };
const sevRank = (s) => SEV.indexOf(s);
const ER_LOCK_DEADLOCK = 1213;
const ER_LOCK_WAIT_TIMEOUT = 1205;
const ER_DUP_ENTRY = 1062;

// ---- validation helpers -----------------------------------------------------

/** Canonicalises + de-duplicates district names; unknown districts are a 422, never silently dropped. */
function normalizeDistricts(list) {
  if (list === undefined || list === null) return null;
  if (!Array.isArray(list)) throw new AppError('districts must be a list.', HTTP_STATUS.UNPROCESSABLE_ENTITY);
  const out = [];
  list.forEach((d) => {
    const canonical = canonicalDistrict(d);
    if (!canonical) throw new AppError(`Unknown district: ${String(d).slice(0, 60)}.`, HTTP_STATUS.UNPROCESSABLE_ENTITY, 'UNKNOWN_DISTRICT');
    if (!out.includes(canonical)) out.push(canonical);
  });
  return out;
}

function assertIncidentEligible(incident) {
  if (!incident) throw new AppError('Incident not found.', HTTP_STATUS.NOT_FOUND);
  if (incident.verification_status !== 'verified' || !RELIEF.OPEN_INCIDENT_STATUSES.includes(incident.status)) {
    throw new AppError(
      'Alerts can only be issued for incidents that an administrator has verified and that are still verified or active.',
      HTTP_STATUS.CONFLICT, 'INCIDENT_NOT_ELIGIBLE'
    );
  }
}

function assertScopeSeverity(scope, severity) {
  // Mass-notification safeguard: a nationwide alert must be at least "high".
  if (scope === 'nationwide' && sevRank(severity) < sevRank('high')) {
    throw new AppError('Nationwide alerts must be High priority or Critical emergency.', HTTP_STATUS.UNPROCESSABLE_ENTITY, 'NATIONWIDE_SEVERITY_TOO_LOW');
  }
}

function resolveTargeting(incident, input, current = null) {
  const scope = input.scope ?? current?.scope ?? 'local';
  let districts = normalizeDistricts(input.districts);
  if (districts === null) districts = current?.districts ?? [incident.district].map((d) => canonicalDistrict(d) || d);
  if (districts.length === 0 && scope !== 'nationwide') districts = [canonicalDistrict(incident.district) || incident.district];
  let radiusKm = input.radiusKm !== undefined ? input.radiusKm : (current ? current.radius_km : null);
  if (scope === 'nationwide') radiusKm = radiusKm ?? null;
  else if (radiusKm === null || radiusKm === undefined) radiusKm = A.DEFAULT_RADIUS_KM;
  return { scope, districts, radiusKm };
}

function incidentView(row) {
  return {
    id: row.incident_id ?? row.id,
    title: row.incident_title ?? row.title,
    disasterType: row.incident_type ?? row.disaster_type,
    disasterTypeLabel: typeLabel(row.incident_type ?? row.disaster_type),
    district: row.incident_district ?? row.district,
    affectedArea: row.incident_affected_area ?? row.affected_area ?? null,
    status: row.incident_status ?? row.status,
    verificationStatus: row.incident_verification_status ?? row.verification_status,
    updatedAt: row.incident_updated_at ?? row.updated_at,
  };
}

/** Public-safe by default; admin fields are added only for the admin views. */
function serializeAlert(row, districts, { admin = false } = {}) {
  const out = {
    id: row.id,
    incidentId: row.incident_id,
    scope: row.scope,
    severity: row.severity,
    severityLabel: severityLabel(row.severity),
    status: row.status,
    radiusKm: row.radius_km,
    adminNote: row.admin_note,
    districts,
    version: row.version,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    resolvedAt: row.resolved_at,
    incident: incidentView(row),
  };
  if (admin) {
    out.autoGenerated = Boolean(row.auto_generated);
    out.createdByName = row.created_by_name ?? null;
    out.cancelledAt = row.cancelled_at;
    out.cancelReason = row.cancel_reason;
    if (row.delivered_total !== undefined) {
      out.deliveredTotal = Number(row.delivered_total);
      out.eventsPending = Number(row.events_pending);
      out.eventsFailed = Number(row.events_failed);
    }
  }
  return out;
}

function recordEvent(connection, alert, eventType, { dedupeKey, note = null, actorId = null, reliefRequestId = null, severity, scope }) {
  return alertModel.insertEvent({
    alertId: alert.id, incidentId: alert.incident_id, eventType, dedupeKey,
    severity: severity ?? alert.severity, scope: scope ?? alert.scope, reliefRequestId, note, createdBy: actorId,
  }, connection);
}

const isRetryableDbError = (err) => err && (err.errno === ER_LOCK_DEADLOCK || err.errno === ER_LOCK_WAIT_TIMEOUT);

// ---- admin operations ---------------------------------------------------------

async function previewAlert(input) {
  const incident = await disasterIncidentModel.findById(input.incidentId);
  if (!incident) throw new AppError('Incident not found.', HTTP_STATUS.NOT_FOUND);
  const severity = input.severity ?? incident.severity;
  const { scope, districts, radiusKm } = resolveTargeting(incident, input);
  assertScopeSeverity(scope, severity);

  const eligible = incident.verification_status === 'verified' && RELIEF.OPEN_INCIDENT_STATUSES.includes(incident.status);
  const live = await alertModel.findLiveByIncident(incident.id);
  const [requests] = await pool.query(
    "SELECT id, title, location_name, priority FROM relief_requests WHERE incident_id = :id AND status = 'approved' ORDER BY id", { id: incident.id }
  );
  const itemRows = await reliefItemModel.findWithTotalsByRequestIds(requests.map((r) => r.id));
  const relief = requests.map((r) => ({
    id: r.id, title: r.title, locationName: r.location_name, priority: r.priority,
    items: itemRows.filter((i) => i.relief_request_id === r.id).map(serializeItem),
  }));

  const audienceSize = eligible ? await audienceModel.countRecipients({
    alert: { id: 0, scope, severity, radius_km: radiusKm }, incident, districts, eventType: 'issued',
  }) : 0;

  return {
    eligible,
    existingLiveAlertId: live ? live.id : null,
    incident: {
      id: incident.id, title: incident.title, disasterType: incident.disaster_type, severity: incident.severity,
      status: incident.status, verificationStatus: incident.verification_status, district: incident.district,
      affectedArea: incident.affected_area, verifiedAt: incident.verified_at, updatedAt: incident.updated_at,
      hasCoordinates: incident.latitude !== null && incident.longitude !== null,
    },
    proposed: { scope, severity, severityLabel: severityLabel(severity), districts, radiusKm },
    relief,
    audienceSize,
    mandatory: scope === 'nationwide' && severity === 'critical',
  };
}

async function issueAlert(user, input, ctx = {}) {
  const { alertId, eventId } = await runInTransaction(async (connection) => {
    const incident = await disasterIncidentModel.findByIdForUpdate(input.incidentId, connection);
    assertIncidentEligible(incident);
    const existing = await alertModel.findLiveByIncident(incident.id, connection, { forUpdate: true });
    if (existing) {
      throw new AppError('This incident already has an active alert. Update or resolve it instead.', HTTP_STATUS.CONFLICT, 'ALERT_ALREADY_ACTIVE');
    }
    const severity = input.severity ?? incident.severity;
    const { scope, districts, radiusKm } = resolveTargeting(incident, input);
    assertScopeSeverity(scope, severity);

    let id;
    try {
      id = await alertModel.createAlert({
        incidentId: incident.id, scope, severity, radiusKm, adminNote: input.note || null, createdBy: user.id,
      }, connection);
    } catch (err) {
      if (err.errno === ER_DUP_ENTRY) throw new AppError('This incident already has an active alert.', HTTP_STATUS.CONFLICT, 'ALERT_ALREADY_ACTIVE');
      throw err;
    }
    await alertModel.replaceDistricts(id, districts, connection);
    const alert = await alertModel.findAlertByIdForUpdate(id, connection);
    const ev = await recordEvent(connection, alert, 'issued', { dedupeKey: `alert:${id}:issued`, note: input.note || null, actorId: user.id });
    return { alertId: id, eventId: ev.id };
  });

  await auditService.record({
    userId: user.id, action: AUDIT_ACTIONS.DISASTER_ALERT_ISSUED, ipAddress: ctx.ipAddress, userAgent: ctx.userAgent,
    metadata: { alertId, incidentId: input.incidentId, scope: input.scope, severity: input.severity ?? null },
  });
  dispatcher.dispatchSoon(eventId);
  return getAlert(alertId);
}

async function updateAlert(id, user, input, ctx = {}) {
  const requestKey = input.requestKey ? String(input.requestKey) : null;
  const replayKey = requestKey ? `alert:${id}:req:${requestKey}` : null;
  if (replayKey) {
    const prior = await alertModel.findEventByDedupeKey(replayKey);
    if (prior) return getAlert(id); // double-submit / retry of the same request: nothing new
  }

  const out = await runInTransaction(async (connection) => {
    const alert = await alertModel.findAlertByIdForUpdate(id, connection);
    if (!alert) throw new AppError('Alert not found.', HTTP_STATUS.NOT_FOUND);
    if (alert.status !== A.STATUS.ACTIVE) throw new AppError('Only an active alert can be updated.', HTTP_STATUS.CONFLICT, 'ALERT_NOT_ACTIVE');
    const incident = await disasterIncidentModel.findByIdForUpdate(alert.incident_id, connection);
    assertIncidentEligible(incident);

    const currentDistricts = await alertModel.getDistricts(id, connection);
    const next = resolveTargeting(incident, input, { scope: alert.scope, districts: currentDistricts, radius_km: alert.radius_km });
    const severity = input.severity ?? alert.severity;
    assertScopeSeverity(next.scope, severity);
    const noteChanged = input.note !== undefined && (input.note || null) !== alert.admin_note;
    const adminNote = input.note !== undefined ? (input.note || null) : alert.admin_note;

    const sevChanged = severity !== alert.severity;
    const scopeChanged = next.scope !== alert.scope;
    const addedDistricts = next.districts.filter((d) => !currentDistricts.includes(d));
    const districtsChanged = addedDistricts.length > 0 || next.districts.length !== currentDistricts.length;
    const radiusChanged = (next.radiusKm ?? null) !== (alert.radius_km ?? null);
    if (!sevChanged && !scopeChanged && !districtsChanged && !radiusChanged && !noteChanged) {
      throw new AppError('No changes to apply.', HTTP_STATUS.UNPROCESSABLE_ENTITY, 'NO_CHANGES');
    }

    const widened = SCOPE_RANK[next.scope] > SCOPE_RANK[alert.scope] || addedDistricts.length > 0
      || (next.radiusKm ?? 0) > (alert.radius_km ?? 0);
    let eventType = 'updated';
    if (sevRank(severity) > sevRank(alert.severity)) eventType = 'escalated';
    else if (widened) eventType = 'area_expanded';

    const version = alert.version + 1;
    await alertModel.updateAlertById(id, {
      severity, scope: next.scope, radius_km: next.radiusKm, admin_note: adminNote, version, updated_by: user.id,
    }, connection);
    if (districtsChanged) await alertModel.replaceDistricts(id, next.districts, connection);
    const ev = await recordEvent(connection, alert, eventType, {
      dedupeKey: replayKey || `alert:${id}:v${version}`, note: input.note || null, actorId: user.id, severity, scope: next.scope,
    });
    return { eventId: ev.id, created: ev.created, eventType, from: { severity: alert.severity, scope: alert.scope }, to: { severity, scope: next.scope } };
  });

  await auditService.record({
    userId: user.id,
    action: out.eventType === 'escalated' ? AUDIT_ACTIONS.DISASTER_ALERT_ESCALATED : AUDIT_ACTIONS.DISASTER_ALERT_UPDATED,
    ipAddress: ctx.ipAddress, userAgent: ctx.userAgent,
    metadata: { alertId: id, eventType: out.eventType, from: out.from, to: out.to },
  });
  if (out.created) dispatcher.dispatchSoon(out.eventId);
  return getAlert(id);
}

async function addCorrection(id, user, { note }, ctx = {}) {
  const out = await runInTransaction(async (connection) => {
    const alert = await alertModel.findAlertByIdForUpdate(id, connection);
    if (!alert) throw new AppError('Alert not found.', HTTP_STATUS.NOT_FOUND);
    if (alert.status === A.STATUS.CANCELLED) throw new AppError('This alert was cancelled.', HTTP_STATUS.CONFLICT, 'ALERT_CANCELLED');
    const version = alert.version + 1;
    await alertModel.updateAlertById(id, { version, updated_by: user.id }, connection);
    const ev = await recordEvent(connection, alert, 'correction', { dedupeKey: `alert:${id}:v${version}`, note, actorId: user.id });
    return ev;
  });
  await auditService.record({
    userId: user.id, action: AUDIT_ACTIONS.DISASTER_ALERT_CORRECTED, ipAddress: ctx.ipAddress, userAgent: ctx.userAgent,
    metadata: { alertId: id },
  });
  dispatcher.dispatchSoon(out.id);
  return getAlert(id);
}

async function resolveAlert(id, user, { note } = {}, ctx = {}) {
  const out = await runInTransaction(async (connection) => {
    const alert = await alertModel.findAlertByIdForUpdate(id, connection);
    if (!alert) throw new AppError('Alert not found.', HTTP_STATUS.NOT_FOUND);
    if (alert.status !== A.STATUS.ACTIVE) throw new AppError('Only an active alert can be resolved.', HTTP_STATUS.CONFLICT, 'ALERT_NOT_ACTIVE');
    await alertModel.updateAlertById(id, { status: A.STATUS.RESOLVED, resolved_at: new Date(), updated_by: user.id, version: alert.version + 1 }, connection);
    return recordEvent(connection, alert, 'resolved', { dedupeKey: `alert:${id}:resolved`, note: note || null, actorId: user.id });
  });
  await auditService.record({
    userId: user.id, action: AUDIT_ACTIONS.DISASTER_ALERT_RESOLVED, ipAddress: ctx.ipAddress, userAgent: ctx.userAgent,
    metadata: { alertId: id },
  });
  dispatcher.dispatchSoon(out.id);
  return getAlert(id);
}

async function cancelAlert(id, user, { reason }, ctx = {}) {
  const out = await runInTransaction(async (connection) => {
    const alert = await alertModel.findAlertByIdForUpdate(id, connection);
    if (!alert) throw new AppError('Alert not found.', HTTP_STATUS.NOT_FOUND);
    if (alert.status === A.STATUS.CANCELLED) throw new AppError('This alert is already cancelled.', HTTP_STATUS.CONFLICT, 'ALERT_NOT_ACTIVE');
    await alertModel.updateAlertById(id, {
      status: A.STATUS.CANCELLED, cancelled_at: new Date(), cancelled_by: user.id, cancel_reason: reason, updated_by: user.id, version: alert.version + 1,
    }, connection);
    return recordEvent(connection, alert, 'cancelled', { dedupeKey: `alert:${id}:cancelled`, actorId: user.id });
  });
  await auditService.record({
    userId: user.id, action: AUDIT_ACTIONS.DISASTER_ALERT_CANCELLED, ipAddress: ctx.ipAddress, userAgent: ctx.userAgent,
    metadata: { alertId: id, reason },
  });
  dispatcher.dispatchSoon(out.id);
  return getAlert(id);
}

async function retryEvent(alertId, eventId, user, ctx = {}) {
  const event = await alertModel.findEventById(eventId);
  if (!event || event.alert_id !== alertId) throw new AppError('Alert event not found.', HTTP_STATUS.NOT_FOUND);
  const requeued = await alertModel.requeueFailedEvent(eventId);
  if (!requeued) throw new AppError('Only a failed delivery can be retried.', HTTP_STATUS.CONFLICT, 'EVENT_NOT_FAILED');
  await auditService.record({
    userId: user.id, action: AUDIT_ACTIONS.DISASTER_ALERT_EVENT_RETRIED, ipAddress: ctx.ipAddress, userAgent: ctx.userAgent,
    metadata: { alertId, eventId },
  });
  dispatcher.dispatchSoon(eventId);
  return getAlert(alertId);
}

// ---- reads ---------------------------------------------------------------------

async function listAlerts(query) {
  const { page, limit, offset } = getPaginationParams(query);
  const filters = { status: query.status, scope: query.scope, severity: query.severity, incidentId: query.incidentId ? Number(query.incidentId) : undefined };
  const [rows, total] = await Promise.all([alertModel.findAllAlerts(filters, { limit, offset }), alertModel.countAllAlerts(filters)]);
  const districts = await alertModel.getDistrictsForAlerts(rows.map((r) => r.id));
  return {
    alerts: rows.map((r) => serializeAlert(r, districts.get(r.id) || [], { admin: true })),
    meta: buildPaginationMeta({ page, limit, totalItems: total }),
  };
}

async function getAlert(id) {
  const row = await alertModel.findAlertById(id);
  if (!row) throw new AppError('Alert not found.', HTTP_STATUS.NOT_FOUND);
  const [districts, events, stats] = await Promise.all([
    alertModel.getDistricts(id), alertModel.listEvents(id), alertModel.getDeliveryStats(id),
  ]);
  const [requests] = await pool.query(
    "SELECT id, title, status FROM relief_requests WHERE incident_id = :id AND status IN ('approved', 'completed') ORDER BY id", { id: row.incident_id }
  );
  return {
    ...serializeAlert(row, districts, { admin: true }),
    stats,
    relief: requests.map((r) => ({ id: r.id, title: r.title, status: r.status })),
    events: events.map((e) => ({
      id: e.id, type: e.event_type, severity: e.severity, scope: e.scope, note: e.note, title: e.title, message: e.message,
      status: e.status, attempts: e.attempts, processedAt: e.processed_at, error: e.last_error,
      recipientCount: e.recipient_count, readCount: Number(e.read_count), createdAt: e.created_at, createdByName: e.created_by_name,
    })),
  };
}

/** Live alerts visible to every signed-in user (verified incidents only; no admin fields). */
async function listActiveAlerts({ incidentId } = {}) {
  const rows = await alertModel.findActive({ incidentId });
  const districts = await alertModel.getDistrictsForAlerts(rows.map((r) => r.id));
  return rows.map((r) => serializeAlert(r, districts.get(r.id) || []));
}

// ---- lifecycle hooks (called INSIDE the caller's transaction so the event row is atomic with the change) ----

async function autoIssueLocal(connection, incident, actorId) {
  const min = alertConfig.autoLocalMinSeverity();
  if (!min || sevRank(incident.severity) < sevRank(min)) return [];
  if (incident.verification_status !== 'verified' || !RELIEF.OPEN_INCIDENT_STATUSES.includes(incident.status)) return [];
  const live = await alertModel.findLiveByIncident(incident.id, connection, { forUpdate: true });
  if (live) return [];
  const id = await alertModel.createAlert({
    incidentId: incident.id, scope: 'local', severity: incident.severity, radiusKm: A.DEFAULT_RADIUS_KM, createdBy: actorId, autoGenerated: true,
  }, connection);
  await alertModel.replaceDistricts(id, [canonicalDistrict(incident.district) || incident.district], connection);
  const alert = await alertModel.findAlertByIdForUpdate(id, connection);
  const ev = await recordEvent(connection, alert, 'issued', { dedupeKey: `alert:${id}:issued`, actorId });
  await auditService.record({
    userId: actorId, action: AUDIT_ACTIONS.DISASTER_ALERT_AUTO_ISSUED,
    metadata: { alertId: id, incidentId: incident.id, severity: incident.severity, scope: 'local' },
  });
  return [ev.id];
}

/**
 * Incident status changed (called from disasterIncident.service#changeStatus).
 * @returns {Promise<number[]>} event ids to dispatch AFTER the transaction commits
 */
async function onIncidentStatusChange(connection, { incident, to, actorId }) {
  try {
    if (to === 'resolved' || to === 'rejected' || to === 'merged') {
      const live = await alertModel.findLiveByIncident(incident.id, connection, { forUpdate: true });
      if (!live) return [];
      if (to === 'resolved') {
        await alertModel.updateAlertById(live.id, { status: A.STATUS.RESOLVED, resolved_at: new Date(), updated_by: actorId, version: live.version + 1 }, connection);
        return [(await recordEvent(connection, live, 'resolved', { dedupeKey: `alert:${live.id}:resolved`, actorId })).id];
      }
      await alertModel.updateAlertById(live.id, {
        status: A.STATUS.CANCELLED, cancelled_at: new Date(), cancelled_by: actorId, cancel_reason: to === 'merged' ? 'Incident was merged into another incident' : 'Incident was rejected', updated_by: actorId, version: live.version + 1,
      }, connection);
      return [(await recordEvent(connection, live, 'cancelled', { dedupeKey: `alert:${live.id}:cancelled`, actorId })).id];
    }
    if (to === 'verified' || to === 'active') return await autoIssueLocal(connection, incident, actorId);
    return [];
  } catch (err) {
    if (isRetryableDbError(err)) throw err;
    console.error('[Alerts] onIncidentStatusChange hook failed:', err.message);
    return [];
  }
}

/** Incident severity edited by an admin; escalates the live alert (or auto-issues) when it went UP. */
async function onIncidentSeverityChange(connection, { before, after, actorId }) {
  try {
    if (sevRank(after.severity) <= sevRank(before.severity)) return [];
    if (after.verification_status !== 'verified' || !RELIEF.OPEN_INCIDENT_STATUSES.includes(after.status)) return [];
    const live = await alertModel.findLiveByIncident(after.id, connection, { forUpdate: true });
    if (!live) return autoIssueLocal(connection, after, actorId);
    if (sevRank(after.severity) <= sevRank(live.severity)) return [];
    const version = live.version + 1;
    await alertModel.updateAlertById(live.id, { severity: after.severity, version, updated_by: actorId }, connection);
    const ev = await recordEvent(connection, live, 'escalated', { dedupeKey: `alert:${live.id}:v${version}`, actorId, severity: after.severity });
    return [ev.id];
  } catch (err) {
    if (isRetryableDbError(err)) throw err;
    console.error('[Alerts] onIncidentSeverityChange hook failed:', err.message);
    return [];
  }
}

/** A relief request was approved: tell the alert's audience about the NEW approved need (once per request). */
async function onReliefRequestApproved(connection, { requestId, incidentId, actorId }) {
  try {
    const live = await alertModel.findLiveByIncident(incidentId, connection, { forUpdate: true });
    if (!live) return [];
    const ev = await recordEvent(connection, live, 'relief_update', {
      dedupeKey: `alert:${live.id}:relief:${requestId}:approved`, actorId, reliefRequestId: requestId,
    });
    return ev.created ? [ev.id] : [];
  } catch (err) {
    if (isRetryableDbError(err)) throw err;
    console.error('[Alerts] onReliefRequestApproved hook failed:', err.message);
    return [];
  }
}

/** Requested quantity of an approved request changed: at most ONE relief update per request per hour. */
async function onReliefQuantityChanged(connection, { requestId, incidentId, actorId, now = Date.now() }) {
  try {
    const live = await alertModel.findLiveByIncident(incidentId, connection, { forUpdate: true });
    if (!live) return [];
    const bucket = Math.floor(now / 3600000);
    const ev = await recordEvent(connection, live, 'relief_update', {
      dedupeKey: `alert:${live.id}:relief:${requestId}:qty:${bucket}`, actorId, reliefRequestId: requestId,
    });
    return ev.created ? [ev.id] : [];
  } catch (err) {
    if (isRetryableDbError(err)) throw err;
    console.error('[Alerts] onReliefQuantityChanged hook failed:', err.message);
    return [];
  }
}

