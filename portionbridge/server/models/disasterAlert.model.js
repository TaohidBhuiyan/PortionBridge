const { pool } = require('../config/db');

/**
 * Raw SQL data-access layer for `disaster_alerts`, `disaster_alert_districts` and
 * `disaster_alert_events` (the delivery outbox). Every write takes an optional
 * `executor` so callers can include it in a transaction.
 */

const ALERT_WRITABLE = new Set(['scope', 'severity', 'status', 'radius_km', 'admin_note', 'version', 'updated_by',
  'resolved_at', 'cancelled_at', 'cancelled_by', 'cancel_reason']);

const ALERT_SELECT = `
  a.*, di.title AS incident_title, di.disaster_type AS incident_type, di.district AS incident_district,
  di.affected_area AS incident_affected_area, di.status AS incident_status,
  di.severity AS incident_severity, di.verification_status AS incident_verification_status,
  di.latitude AS incident_latitude, di.longitude AS incident_longitude, di.updated_at AS incident_updated_at,
  creator.name AS created_by_name
  FROM disaster_alerts a
  JOIN disaster_incidents di ON di.id = a.incident_id
  LEFT JOIN users creator ON creator.id = a.created_by
`;

async function createAlert(data, executor = pool) {
  const [result] = await executor.query(
    `INSERT INTO disaster_alerts (incident_id, scope, severity, radius_km, admin_note, auto_generated, created_by, updated_by)
     VALUES (:incidentId, :scope, :severity, :radiusKm, :adminNote, :autoGenerated, :createdBy, :createdBy)`,
    {
      incidentId: data.incidentId, scope: data.scope, severity: data.severity, radiusKm: data.radiusKm ?? null,
      adminNote: data.adminNote ?? null, autoGenerated: data.autoGenerated ? 1 : 0, createdBy: data.createdBy ?? null,
    }
  );
  return result.insertId;
}

async function findAlertById(id, executor = pool) {
  const [rows] = await executor.query(`SELECT ${ALERT_SELECT} WHERE a.id = :id`, { id });
  return rows[0] || null;
}

/** Row lock — call inside a transaction. */
async function findAlertByIdForUpdate(id, connection) {
  const [rows] = await connection.query('SELECT * FROM disaster_alerts WHERE id = :id FOR UPDATE', { id });
  return rows[0] || null;
}

/** The single live alert for an incident (the DB guarantees at most one). */
async function findLiveByIncident(incidentId, executor = pool, { forUpdate = false } = {}) {
  const [rows] = await executor.query(
    `SELECT * FROM disaster_alerts WHERE incident_id = :incidentId AND status = 'active' LIMIT 1 ${forUpdate ? 'FOR UPDATE' : ''}`,
    { incidentId }
  );
  return rows[0] || null;
}

async function updateAlertById(id, fields, executor = pool) {
  const keys = Object.keys(fields).filter((k) => ALERT_WRITABLE.has(k));
  if (keys.length === 0) return;
  const params = { id };
  keys.forEach((k) => { params[k] = fields[k]; });
  await executor.query(`UPDATE disaster_alerts SET ${keys.map((k) => `${k} = :${k}`).join(', ')} WHERE id = :id`, params);
}

async function getDistricts(alertId, executor = pool) {
  const [rows] = await executor.query('SELECT district FROM disaster_alert_districts WHERE alert_id = :alertId ORDER BY district', { alertId });
  return rows.map((r) => r.district);
}

async function getDistrictsForAlerts(alertIds, executor = pool) {
  const map = new Map();
  if (!alertIds.length) return map;
  const params = {};
  const names = alertIds.map((id, i) => { params[`a${i}`] = id; return `:a${i}`; });
  const [rows] = await executor.query(
    `SELECT alert_id, district FROM disaster_alert_districts WHERE alert_id IN (${names.join(', ')}) ORDER BY district`, params
  );
  rows.forEach((r) => {
    if (!map.has(r.alert_id)) map.set(r.alert_id, []);
    map.get(r.alert_id).push(r.district);
  });
  return map;
}

async function replaceDistricts(alertId, districts, executor = pool) {
  await executor.query('DELETE FROM disaster_alert_districts WHERE alert_id = :alertId', { alertId });
  if (!districts.length) return;
  const params = { alertId };
  const values = districts.map((d, i) => { params[`d${i}`] = d; return `(:alertId, :d${i})`; });
  await executor.query(`INSERT INTO disaster_alert_districts (alert_id, district) VALUES ${values.join(', ')}`, params);
}

function buildFilter({ status, scope, severity, incidentId }) {
  const conditions = ['1 = 1'];
  const params = {};
  if (status) { conditions.push('a.status = :status'); params.status = status; }
  if (scope) { conditions.push('a.scope = :scope'); params.scope = scope; }
  if (severity) { conditions.push('a.severity = :severity'); params.severity = severity; }
  if (incidentId) { conditions.push('a.incident_id = :incidentId'); params.incidentId = incidentId; }
  return { where: conditions.join(' AND '), params };
}

/** Alert history with delivery statistics derived from the notifications actually stored. */
async function findAllAlerts(filters, { limit, offset }) {
  const { where, params } = buildFilter(filters);
  const [rows] = await pool.query(
    `SELECT ${ALERT_SELECT.replace('FROM disaster_alerts a', `,
      (SELECT COALESCE(SUM(e.recipient_count), 0) FROM disaster_alert_events e WHERE e.alert_id = a.id AND e.status = 'completed') AS delivered_total,
      (SELECT COUNT(*) FROM disaster_alert_events e WHERE e.alert_id = a.id AND e.status IN ('pending', 'processing')) AS events_pending,
      (SELECT COUNT(*) FROM disaster_alert_events e WHERE e.alert_id = a.id AND e.status = 'failed') AS events_failed
     FROM disaster_alerts a`)}
     WHERE ${where} ORDER BY a.created_at DESC, a.id DESC LIMIT :limit OFFSET :offset`,
    { ...params, limit, offset }
  );
  return rows;
}

async function countAllAlerts(filters) {
  const { where, params } = buildFilter(filters);
  const [rows] = await pool.query(`SELECT COUNT(*) AS total FROM disaster_alerts a WHERE ${where}`, params);
  return rows[0].total;
}

/** Publicly visible live alerts (verified incidents only), newest update first. */
async function findActive({ incidentId } = {}, executor = pool) {
  const params = {};
  let extra = '';
  if (incidentId) { extra = 'AND a.incident_id = :incidentId'; params.incidentId = incidentId; }
  const [rows] = await executor.query(
    `SELECT ${ALERT_SELECT} WHERE a.status = 'active' AND di.verification_status = 'verified' ${extra}
     ORDER BY FIELD(a.severity, 'critical', 'high', 'moderate', 'low'), a.updated_at DESC LIMIT 50`,
    params
  );
  return rows;
}

