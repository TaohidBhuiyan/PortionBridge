/**
 * Inserts an outbox event. The unique dedupe_key makes this idempotent: when the
 * key already exists the existing event id is returned with `created: false`.
 */
async function insertEvent(e, executor = pool) {
  const [result] = await executor.query(
    `INSERT IGNORE INTO disaster_alert_events
       (alert_id, incident_id, event_type, dedupe_key, severity, scope, relief_request_id, note, created_by)
     VALUES (:alertId, :incidentId, :eventType, :dedupeKey, :severity, :scope, :reliefRequestId, :note, :createdBy)`,
    {
      alertId: e.alertId, incidentId: e.incidentId, eventType: e.eventType, dedupeKey: e.dedupeKey,
      severity: e.severity, scope: e.scope, reliefRequestId: e.reliefRequestId ?? null,
      note: e.note ?? null, createdBy: e.createdBy ?? null,
    }
  );
  if (result.affectedRows === 1 && result.insertId) return { id: result.insertId, created: true };
  const [rows] = await executor.query('SELECT id FROM disaster_alert_events WHERE dedupe_key = :k', { k: e.dedupeKey });
  return { id: rows[0] ? rows[0].id : null, created: false };
}

async function findEventById(id, executor = pool) {
  const [rows] = await executor.query('SELECT * FROM disaster_alert_events WHERE id = :id', { id });
  return rows[0] || null;
}

async function findEventByDedupeKey(dedupeKey, executor = pool) {
  const [rows] = await executor.query('SELECT * FROM disaster_alert_events WHERE dedupe_key = :dedupeKey', { dedupeKey });
  return rows[0] || null;
}

async function listEvents(alertId, executor = pool) {
  const [rows] = await executor.query(
    `SELECT e.id, e.alert_id, e.event_type, e.severity, e.scope, e.relief_request_id, e.note, e.title, e.message,
            e.status, e.attempts, e.processed_at, e.last_error, e.recipient_count, e.created_at, u.name AS created_by_name,
            (SELECT COUNT(*) FROM notifications n WHERE n.alert_event_id = e.id AND n.is_read = 1) AS read_count
     FROM disaster_alert_events e LEFT JOIN users u ON u.id = e.created_by
     WHERE e.alert_id = :alertId ORDER BY e.created_at DESC, e.id DESC`,
    { alertId }
  );
  return rows;
}

/**
 * Atomically claims an event for processing. Exactly one caller wins (affectedRows = 1);
 * a pending event, a failed event under the attempt cap, or a 'processing' claim that
 * went stale (crashed worker) can be claimed. Completed events are never re-claimed.
 */
async function claimEvent(id, { maxAttempts, staleSeconds }) {
  const [result] = await pool.query(
    `UPDATE disaster_alert_events
        SET status = 'processing', locked_at = NOW(), attempts = attempts + 1, last_error = NULL
      WHERE id = :id AND attempts < :maxAttempts
        AND (status IN ('pending', 'failed')
             OR (status = 'processing' AND locked_at < (NOW() - INTERVAL :staleSeconds SECOND)))`,
    { id, maxAttempts, staleSeconds }
  );
  return result.affectedRows === 1;
}

async function completeEvent(id, { title, message, recipientCount, skipReason = null }) {
  await pool.query(
    `UPDATE disaster_alert_events
        SET status = 'completed', title = :title, message = :message, recipient_count = :recipientCount,
            processed_at = NOW(), locked_at = NULL, last_error = :skipReason
      WHERE id = :id`,
    { id, title: title ?? null, message: message ?? null, recipientCount, skipReason: skipReason ? `skipped: ${skipReason}` : null }
  );
}

async function failEvent(id, errorMessage) {
  await pool.query(
    `UPDATE disaster_alert_events SET status = 'failed', locked_at = NULL, last_error = :err WHERE id = :id`,
    { id, err: String(errorMessage || 'Unknown error').slice(0, 500) }
  );
}

/** Admin retry: puts a failed event back in the queue with a fresh attempt budget. */
async function requeueFailedEvent(id) {
  const [result] = await pool.query(
    `UPDATE disaster_alert_events SET status = 'pending', attempts = 0, last_error = NULL, locked_at = NULL
      WHERE id = :id AND status = 'failed'`,
    { id }
  );
  return result.affectedRows === 1;
}

/** Ids the sweeper should (re)process: pending, failed under the cap, or stale claims. */
async function findRunnableEventIds({ maxAttempts, staleSeconds, limit = 50 }) {
  const [rows] = await pool.query(
    `SELECT id FROM disaster_alert_events
      WHERE attempts < :maxAttempts
        AND (status IN ('pending', 'failed')
             OR (status = 'processing' AND locked_at < (NOW() - INTERVAL :staleSeconds SECOND)))
      ORDER BY created_at ASC, id ASC LIMIT :limit`,
    { maxAttempts, staleSeconds, limit }
  );
  return rows.map((r) => r.id);
}

/** Read / unread / total counts of the notifications stored for an alert (delivery statistics). */
async function getDeliveryStats(alertId, executor = pool) {
  const [rows] = await executor.query(
    `SELECT COUNT(*) AS delivered, COALESCE(SUM(n.is_read = 1), 0) AS read_count
       FROM notifications n JOIN disaster_alert_events e ON e.id = n.alert_event_id
      WHERE e.alert_id = :alertId`,
    { alertId }
  );
  const [uniq] = await executor.query(
    `SELECT COUNT(DISTINCT n.user_id) AS unique_recipients
       FROM notifications n JOIN disaster_alert_events e ON e.id = n.alert_event_id WHERE e.alert_id = :alertId`,
    { alertId }
  );
  return {
    notificationsStored: Number(rows[0].delivered),
    read: Number(rows[0].read_count),
    unread: Number(rows[0].delivered) - Number(rows[0].read_count),
    uniqueRecipients: Number(uniq[0].unique_recipients),
  };
}

