import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor, within } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';

vi.mock('../services/alertApi', () => ({
  default: { list: vi.fn(), get: vi.fn(), preview: vi.fn(), issue: vi.fn(), update: vi.fn(), correct: vi.fn(), resolve: vi.fn(), cancel: vi.fn(), retryEvent: vi.fn() },
}));
vi.mock('../services/reliefApi', () => ({ default: { listIncidents: vi.fn() } }));
vi.mock('react-hot-toast', () => ({ default: { success: vi.fn(), error: vi.fn() } }));
vi.mock('../components/dashboard', async (importOriginal) => ({
  ...(await importOriginal()),
  DashboardLayout: ({ children }) => <div>{children}</div>,
}));

import alertApi from '../services/alertApi';
import reliefApi from '../services/reliefApi';
import { AdminAlertsPage } from './AdminAlertsPage';

const incident = { id: 5, title: 'Flood in Sylhet', district: 'Sylhet', status: 'verified', verificationStatus: 'verified', updatedAt: '2026-10-19T10:00:00Z' };
const alertRow = (o = {}) => ({
  id: 9, incidentId: 5, scope: 'nationwide', severity: 'critical', status: 'active', districts: ['Sylhet'], radiusKm: null, adminNote: null,
  autoGenerated: false, incident, updatedAt: '2026-10-19T10:00:00Z', deliveredTotal: 120, eventsPending: 0, eventsFailed: 1, ...o,
});
const list = (alerts, meta = {}) => ({ data: { alerts }, meta: { page: 1, limit: 15, totalItems: alerts.length, totalPages: 1, ...meta } });
const detail = (o = {}) => ({
  data: { alert: { ...alertRow(), stats: { notificationsStored: 120, uniqueRecipients: 120, read: 30, unread: 90 }, relief: [],
    events: [{ id: 1, type: 'issued', severity: 'critical', scope: 'nationwide', status: 'failed', recipientCount: 0, readCount: 0, createdAt: '2026-10-19T10:00:00Z', error: 'db down' }], ...o } },
});
const renderPage = () => render(<MemoryRouter><AdminAlertsPage /></MemoryRouter>);

beforeEach(() => {
  vi.clearAllMocks();
  alertApi.list.mockResolvedValue(list([alertRow()]));
  alertApi.get.mockResolvedValue(detail());
  reliefApi.listIncidents.mockResolvedValue({ data: { incidents: [{ ...incident, severity: 'high' }] } });
});

describe('AdminAlertsPage', () => {
  it('lists alert history with severity, status and honest delivery numbers', async () => {
    renderPage();
    const row = await screen.findByTestId('alert-row');
    expect(row.textContent).toMatch(/Flood in Sylhet/);
    expect(row.textContent).toMatch(/Critical emergency/);
    expect(row.textContent).toMatch(/120 sent/);
    expect(row.textContent).toMatch(/1 failed/);
    expect(alertApi.list).toHaveBeenCalledWith({ page: 1, limit: 15 });
  });

  it('shows empty and error states', async () => {
    alertApi.list.mockResolvedValueOnce(list([]));
    const { unmount } = renderPage();
    expect(await screen.findByText(/no alerts yet/i)).toBeTruthy();
    unmount();
    alertApi.list.mockRejectedValueOnce({ response: { status: 500, data: { message: 'nope' } } });
    renderPage();
    expect(await screen.findByText(/could not load alerts/i)).toBeTruthy();
  });

  it('detail shows delivery statistics, notes there is no external channel, and offers retry for failed delivery', async () => {
    alertApi.retryEvent.mockResolvedValue({});
    renderPage();
    fireEvent.click(await screen.findByRole('button', { name: /review & manage/i }));
    const stats = await screen.findByTestId('alert-stats');
    expect(stats.textContent).toMatch(/120/);
    expect(stats.textContent).toMatch(/90/);
    expect(screen.getByText(/no external channel/i)).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /retry delivery/i }));
    await waitFor(() => expect(alertApi.retryEvent).toHaveBeenCalledWith(9, 1));
  });

  it('cancelling requires a reason of at least 5 characters', async () => {
    alertApi.cancel.mockResolvedValue({});
    renderPage();
    fireEvent.click(await screen.findByRole('button', { name: /review & manage/i }));
    fireEvent.click(await screen.findByRole('button', { name: /cancel alert/i }));
    const confirm = screen.getByRole('button', { name: /confirm/i });
    expect(confirm.disabled).toBe(true);
    fireEvent.change(screen.getByLabelText(/reason/i), { target: { value: 'Duplicate of #4' } });
    expect(confirm.disabled).toBe(false);
    fireEvent.click(confirm);
    await waitFor(() => expect(alertApi.cancel).toHaveBeenCalledWith(9, 'Duplicate of #4'));
  });

  it('issuing requires a review step: preview first, publish only when eligible', async () => {
    alertApi.preview.mockResolvedValue({ data: {
      eligible: true, existingLiveAlertId: null, mandatory: true, audienceSize: 42,
      incident: { ...incident, severity: 'high', hasCoordinates: true },
      proposed: { scope: 'nationwide', severity: 'critical', districts: ['Sylhet'], radiusKm: null },
      relief: [{ id: 1, title: 'Shelter', items: [{ name: 'Rice', unit: 'kg', quantities: { requested: 100, remainingToPledge: 60 } }] }],
    } });
    alertApi.issue.mockResolvedValue({});
    renderPage();
    fireEvent.click(await screen.findByRole('button', { name: /^issue alert$/i }));
    await screen.findByRole('option', { name: /Flood in Sylhet/ });
    const publish = screen.getByRole('button', { name: /publish alert/i });
    expect(publish.disabled).toBe(true);
    fireEvent.change(screen.getByLabelText(/verified incident/i), { target: { value: '5' } });
    fireEvent.change(screen.getByLabelText(/^scope/i), { target: { value: 'nationwide' } });
    fireEvent.change(screen.getByLabelText(/^level/i), { target: { value: 'critical' } });
    fireEvent.click(screen.getByRole('button', { name: /review before publishing/i }));
    const preview = await screen.findByTestId('alert-preview');
    expect(within(preview).getByText(/42/)).toBeTruthy();
    expect(preview.textContent).toMatch(/Rice 60 kg still needed/);
    expect(preview.textContent).toMatch(/override recipients/i);
    fireEvent.click(screen.getByRole('button', { name: /publish alert/i }));
    await waitFor(() => expect(alertApi.issue).toHaveBeenCalledWith({ incidentId: 5, scope: 'nationwide', severity: 'critical' }));
  });
});
